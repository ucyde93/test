'use strict';
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('sahifaHost', {
  isDesktop: true,
  platform: process.platform,
  openDialog: (opts) => ipcRenderer.invoke('open-dialog', opts),
  readFile: (p) => ipcRenderer.invoke('read-file', p),
  saveFile: (opts) => ipcRenderer.invoke('save-file', opts),
  saveMany: (opts) => ipcRenderer.invoke('save-many', opts),
  recentGet: () => ipcRenderer.invoke('recent-get'),
  showInFolder: (p) => ipcRenderer.invoke('show-in-folder', p),
  openExternal: (url) => ipcRenderer.invoke('open-external', url),
  appInfo: () => ipcRenderer.invoke('app-info'),
  setDirty: (dirty) => ipcRenderer.send('set-dirty', dirty),
  setTitle: (title) => ipcRenderer.send('set-title', title),
  idsList: () => ipcRenderer.invoke('ids-list'),
  idsCreate: (opts) => ipcRenderer.invoke('ids-create', opts),
  idsImport: (opts) => ipcRenderer.invoke('ids-import', opts),
  idsDelete: (id) => ipcRenderer.invoke('ids-delete', id),
  idsExport: (id) => ipcRenderer.invoke('ids-export', id),
  digitalSign: (opts) => ipcRenderer.invoke('digital-sign', opts),
  onMenu: (cb) => ipcRenderer.on('menu', (_e, cmd, arg) => cb(cmd, arg)),
  onOpenPaths: (cb) => ipcRenderer.on('open-paths', (_e, paths) => cb(paths)),
  rendererReady: () => ipcRenderer.send('renderer-ready'),
  libraryGet: () => ipcRenderer.invoke('library-get'),
  librarySet: (items) => ipcRenderer.invoke('library-set', items),
  libraryStatus: () => ipcRenderer.invoke('library-status'),
  libraryUnlock: (pin) => ipcRenderer.invoke('library-unlock', pin),
  libraryLock: () => ipcRenderer.invoke('library-lock'),
  librarySetPin: (o) => ipcRenderer.invoke('library-set-pin', o),
  libraryRemovePin: (o) => ipcRenderer.invoke('library-remove-pin', o),
  libraryWipeOption: (on) => ipcRenderer.invoke('library-wipe-option', on),
  libraryAutoLock: (m) => ipcRenderer.invoke('library-auto-lock', m),
  libraryReset: () => ipcRenderer.invoke('library-reset'),
  libraryExport: (o) => ipcRenderer.invoke('library-export', o),
  libraryDecryptBackup: (o) => ipcRenderer.invoke('library-decrypt-backup', o),
  libraryActivity: () => ipcRenderer.send('library-activity'),
  onLibraryLocked: (cb) => ipcRenderer.on('library-locked', (_e, reason) => cb(reason)),
  defaultStatus: () => ipcRenderer.invoke('default-status'),
  makeDefault: (opts) => ipcRenderer.invoke('default-set', opts),
  openDefaultSettings: () => ipcRenderer.invoke('default-settings'),
  onDefaultStatus: (cb) => ipcRenderer.on('default-status', (_e, st) => cb(st)),
  setChrome: (theme) => ipcRenderer.send('set-chrome', theme),
  popupMenu: (x, y) => ipcRenderer.send('menu-popup', { x, y }),
});
